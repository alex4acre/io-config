REFERENCE = read(os.path.join(DATA, "controller-eni.xml"))
REFERENCE_INI = read(os.path.join(DATA, "controller-ini.txt"))


class GeneratorTest(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        cls.dir = tempfile.TemporaryDirectory()
        cls.lib = full_library(cls.dir.name)
        cls.current = eni.parse_eni(REFERENCE)

    @classmethod
    def tearDownClass(cls):
        cls.dir.cleanup()

    def esi(self, s):
        return self.lib.device(self.lib.find(s["vendor"], s["product"], s["revision"])[1])

    def test_same_file_from_the_current_configuration(self):
        devices = [generate.apply_eni(generate.device_from_esi(self.esi(s), ""), s) for s in self.current["slaves"]]
        self.assertEqual(generate.generate_eni(devices, "ethercatmaster", 2000), REFERENCE)

    def test_same_file_from_the_esi_alone(self):
        devices = [generate.device_from_esi(self.esi(s), generate.device_name(self.esi(s)["type"]))
                   for s in self.current["slaves"]]
        self.assertEqual([d["name"] for d in devices], ["XB_EC_12", "XI190202", "XI422202", "XI522001"])
        self.assertEqual(generate.generate_eni(devices, "ethercatmaster", 2000), REFERENCE)

    def test_ini_and_checksums(self):
        self.assertEqual(generate.generate_ini(REFERENCE_INI.decode("latin-1"), 2000), REFERENCE_INI)
        self.assertIn(b"CycleTimeUs=1000\r\n", generate.generate_ini(REFERENCE_INI.decode("latin-1"), 1000))
        self.assertEqual(generate.checksum(REFERENCE), [35, 177, 171, 70])          # as the X3 reported
        self.assertEqual(generate.checksum(REFERENCE_INI), [57, 154, 135, 241])

    def test_cycle_time_reaches_dc(self):
        devices = [generate.apply_eni(generate.device_from_esi(self.esi(s), ""), s) for s in self.current["slaves"]]
        out = eni.parse_eni(generate.generate_eni(devices, "ethercatmaster", 1000))
        self.assertEqual(out["slaves"][1]["dc"]["CycleTime0"], "1000000")

    def test_refused_buses(self):
        devices = [generate.apply_eni(generate.device_from_esi(self.esi(s), ""), s) for s in self.current["slaves"]]
        with self.assertRaises(generate.GenerateError):
            generate.generate_eni(devices[:1] * 2, "ethercatmaster", 2000)        # same name twice
        with self.assertRaises(generate.GenerateError):
            generate.generate_eni([], "ethercatmaster", 2000)

    def test_names(self):
        self.assertEqual(generate.variable_name("Ch. 1 Overcurrent"), "Ch_1_Overcurrent")
        self.assertEqual(generate.variable_name("Channel 1 Sample  0"), "Channel_1_Sample_0")
        self.assertEqual(generate.device_name("XB-EC-12"), "XB_EC_12")


class PlanTest(unittest.TestCase):

    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.lib = full_library(self.dir.name)
        rec = recording()
        cur = eni.parse_eni(REFERENCE)
        from app import sii
        self.sources = []
        for pos, s in enumerate(rec["slaves"]):
            idn = s["online_info"]["response"]["slaveIdentity"]
            match, entry = self.lib.find(idn["vendorId"], idn["productCode"], idn["revisionNumber"])
            self.sources.append({"pos": pos, "online": s["online_info"], "eeprom": sii.decode(s["eeprom"]),
                                 "eni_slave": cur["slaves"][pos], "esi_match": match,
                                 "esi_device": self.lib.device(entry) if entry else None})
        self.current = {"eni": REFERENCE, "ini": REFERENCE_INI, "parsed": cur}

    def tearDown(self):
        self.dir.cleanup()

    def test_unchanged_bus_is_identical(self):
        p = build_plan(self.sources, self.current, "ethercatmaster")
        self.assertEqual((p["errors"], p["identical"], p["variables"]), ([], True, {"added": [], "removed": [], "changed": []}))
        self.assertEqual([d["source"] for d in p["devices"]], ["eni"] * 4)

    def test_empty_master_gets_the_same_file_from_the_esi(self):
        for s in self.sources:
            s["eni_slave"] = None
        p = build_plan(self.sources, {"eni": b"", "ini": b"", "parsed": None}, "ethercatmaster")
        self.assertEqual(p["eni"], REFERENCE)
        self.assertEqual(len(p["variables"]["added"]), 44)

    def test_device_without_esi_is_learned_from_the_eeprom(self):
        self.sources[3].update(esi_match="none", esi_device=None, eni_slave=None)
        p = build_plan(self.sources, self.current, "ethercatmaster")
        self.assertEqual(p["errors"], [])
        self.assertEqual(p["devices"][3]["source"], "eeprom")
        self.assertIn("Position 3: no ESI", p["warnings"][0])
        names = [s["name"] for s in eni.parse_eni(p["eni"])["slaves"]]
        self.assertEqual(names, ["XB_EC_12", "XI190202", "XI422202", "XI522001"])
        self.assertFalse(p["identical"])

    def test_cycle_time_change(self):
        p = build_plan(self.sources, self.current, "ethercatmaster", cycle_us=1000)
        self.assertIn(b"CycleTimeUs=1000", p["ini"])
        self.assertFalse(p["identical"])


class DownloadTest(unittest.TestCase):

    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.active = os.path.join(self.dir.name, "activeConfiguration")
        self.bus = FakeBus()
        self.core = Core(os.path.join(self.active, "io-config", "config.json"), self.bus,
                         os.path.join(self.dir.name, "esi"), log=lambda m: None)
        for name in ESI_FILES:
            self.core.esi.add(name, read(os.path.join(ESI_DIR, name)))
        self.core.start_scan()
        self.core.wait_scan()

    def tearDown(self):
        self.core.stop()
        self.dir.cleanup()

    def download(self, cycle_us=None):
        p = self.core.plan(cycle_us)
        self.core.start_download(p["id"])
        self.core.wait_scan()            # the download thread, then the rescan it starts
        self.core.wait_scan()
        return self.core.state()

    def test_download(self):
        s = self.download(cycle_us=1000)
        self.assertIsNone(s["download"]["error"], s["download"])
        self.assertEqual(len(self.bus.written), 1)
        eni_written, ini_written = self.bus.written[0]
        self.assertIn(b"CycleTimeUs=1000", ini_written)
        states = [c[2]["request"]["newState"] for c in self.bus.calls if c[0] == "write" and c[1].endswith("master_state")]
        self.assertEqual(states, ["init", "op"])
        folder = os.path.join(self.active, "comm.ethercat.master", "config", "ethercatmaster")
        self.assertEqual(read(os.path.join(folder, "ethercat.xml")), eni_written)
        self.assertEqual(read(os.path.join(folder, "ethercat.ini")), ini_written)
        backups = self.core.backups()
        self.assertEqual(len(backups), 1)
        self.assertEqual(read(os.path.join(self.core.backup_dir, backups[0]["name"], "ethercat.xml")), REFERENCE)
        self.assertEqual(s["master"]["cycle_us"], 1000)           # rescanned after the download
        self.assertTrue(any("checksums match" in x for x in s["download"]["steps"]))

    def test_restore(self):
        self.download(cycle_us=1000)
        name = self.core.backups()[0]["name"]
        self.core.start_restore(name)
        self.core.wait_scan()
        self.core.wait_scan()
        self.assertEqual(self.bus.written[-1], (REFERENCE, REFERENCE_INI))
        self.assertEqual(self.core.state()["master"]["cycle_us"], 2000)

    def test_stale_plan_and_changed_master_are_refused(self):
        p = self.core.plan()
        self.core.plan()
        with self.assertRaises(ConfigError):
            self.core.start_download(p["id"])
        p = self.core.plan()
        self.bus.nodes[MASTER + "admin/fieldbus_config/checksum"] = {"response": {"checksums": [
            {"id": "eniCrc32", "checksum": [1, 2, 3, 4]}]}}
        self.core.start_download(p["id"])
        self.core.wait_scan()
        self.core.wait_scan()
        self.assertIn("changed since the last scan", self.core.state()["download"]["error"])
        self.assertEqual(self.bus.written, [])

    def test_master_not_reaching_op(self):
        import app.configure
        self.bus.fail_op = True
        old = app.configure._wait_state

        def short(bus, base, wanted, timeout, log):
            return old(bus, base, wanted, min(timeout, 1), log)
        app.configure._wait_state = short
        try:
            s = self.download()
        finally:
            app.configure._wait_state = old
        self.assertIn("did not reach op", s["download"]["error"])
        self.assertEqual(len(self.core.backups()), 1)


class WebTest(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        cls.dir = tempfile.TemporaryDirectory()
        core = Core(os.path.join(cls.dir.name, "active", "io-config", "config.json"), FakeBus(),
                    os.path.join(cls.dir.name, "esi"), log=lambda m: None)
        for name in ESI_FILES:
            core.esi.add(name, read(os.path.join(ESI_DIR, name)))
        app.web.core = core
        app.web.www_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "www")
        cls.server = app.web.TcpServer(("127.0.0.1", 0), app.web.RequestHandler)
        threading.Thread(target=cls.server.serve_forever, daemon=True).start()
        cls.base = f"http://127.0.0.1:{cls.server.server_address[1]}/io-config/api/v1"
        cls.opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))

    @classmethod
    def tearDownClass(cls):
        cls.server.shutdown()
        cls.server.server_close()
        app.web.core.stop()
        cls.dir.cleanup()

    def call(self, method, path, body=None, raw=False):
        req = urllib.request.Request(self.base + path, data=None if body is None else json.dumps(body).encode(),
                                     method=method, headers={"Content-Type": "application/json"})
        try:
            with self.opener.open(req, timeout=10) as r:
                data = r.read()
                return r.status, data if raw else json.loads(data or b"null")
        except urllib.error.HTTPError as e:
            return e.code, json.loads(e.read() or b"null")

    def test_plan_download_backups(self):
        self.assertEqual(self.call("POST", "/plan")[0], 400)           # no scan yet
        self.call("POST", "/scan", {})
        app.web.core.wait_scan()
        status, p = self.call("POST", "/plan", {})
        self.assertEqual((status, p["identical"], p["eni_size"]), (200, True, len(REFERENCE)))
        self.assertEqual(self.call("GET", "/plan/eni", raw=True), (200, REFERENCE))
        self.assertEqual(self.call("POST", "/download", {"plan_id": p["id"]})[0], 400)      # no confirm
        self.assertEqual(self.call("POST", "/download", {"plan_id": p["id"], "confirm": True})[0], 202)
        app.web.core.wait_scan()
        app.web.core.wait_scan()
        status, b = self.call("GET", "/backups")
        self.assertEqual((status, len(b["backups"])), (200, 1))
        name = b["backups"][0]["name"]
        self.assertEqual(self.call("GET", f"/backups/{name}/eni", raw=True), (200, REFERENCE))
        self.assertEqual(self.call("POST", f"/backups/{name}/restore", {})[0], 400)
        self.assertEqual(self.call("GET", "/backups/20990101-000000/eni")[0], 404)


